"""
Register the reset_password_otp WhatsApp template via Meta Graph API.
Run this ONCE from any machine that has internet access:
    python scripts/create_otp_template.py
"""
import httpx
import json

# ── Config ───────────────────────────────────────────────────────────────────
WABA_ID = "1655918325582776"
TOKEN   = (
    "EAAvjtOvrgVUBRC6LFZBvIUSAzINBSKtZCMGu34YXXtjHEmWtq5aww5lt5kxuWkxpYsy6"
    "hDzvmo5jmIDW7ut8gtgEyBhCLtQBvFVw5ZBxDrhpG54TLlCpDTtpli6F9dPkmXW6Aseb2"
    "l8V9yDWtB7l21ZA51rQMvZB6lzvSpX3C9Jd7FxZAdqUKJLrYZCsKarD6DbbgZDZD"
)
# ─────────────────────────────────────────────────────────────────────────────

TEMPLATE_NAME = "souk_reset_otp"   # new name (reset_password_otp was rejected as UTILITY)
REJECTED_TEMPLATE_ID = "3867234663570100"  # delete this first

headers = {
    "Authorization": f"Bearer {TOKEN}",
    "Content-Type": "application/json",
}

# ── Step 0: delete the previously rejected template ──────────
print(f"Deleting rejected template {REJECTED_TEMPLATE_ID}…")
with httpx.Client() as client:
    del_resp = client.delete(
        f"https://graph.facebook.com/v22.0/{REJECTED_TEMPLATE_ID}",
        headers=headers,
        timeout=30,
    )
    print(f"  Delete status: {del_resp.status_code} — {del_resp.text}")

# ── Step 1: create AUTHENTICATION template ───────────────────
url = f"https://graph.facebook.com/v22.0/{WABA_ID}/message_templates"

# AUTHENTICATION category is the correct type for OTP templates.
# Body text is auto-generated by Meta; the {{1}} variable carries the code.
payload = {
    "name": TEMPLATE_NAME,
    "category": "AUTHENTICATION",
    "language": "fr",
    "components": [
        {
            "type": "BODY",
            "add_security_recommendation": True,
        },
        {
            "type": "FOOTER",
            "code_expiration_minutes": 10,
        },
        {
            "type": "BUTTONS",
            "buttons": [
                {
                    "type": "OTP",
                    "otp_type": "COPY_CODE",
                    "text": "Copier le code",
                }
            ],
        },
    ],
}

print(f"\nSubmitting AUTHENTICATION template '{TEMPLATE_NAME}' to Meta API…")
with httpx.Client() as client:
    resp = client.post(url, json=payload, headers=headers, timeout=30)

data = resp.json()
print(f"Status: {resp.status_code}")
print(json.dumps(data, indent=2, ensure_ascii=False))

if resp.status_code == 200 and "id" in data:
    print("\n✅  Template submitted successfully!")
    print(f"   Template name: {TEMPLATE_NAME}")
    print(f"   Template ID  : {data['id']}")
    print(f"   Status       : {data.get('status', 'PENDING')}")
    print("\nNext steps:")
    print("  1. Wait for Meta to approve (usually instant for AUTHENTICATION)")
    print("  2. Check at: https://business.facebook.com/wa/manage/message-templates/")
    print(f"  3. Update TEMPLATE_NAME in backend/services/whatsapp.py to '{TEMPLATE_NAME}'")
    print("  4. Once APPROVED: OTP works for ALL clients, no 24h restriction")
else:
    print("\n❌  Submission failed – see error above.")
    if "error" in data:
        print(f"   Tip: {data['error'].get('message', '')}")
